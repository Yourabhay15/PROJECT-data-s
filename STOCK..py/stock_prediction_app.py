import shutil, random

source_root = os.path.join(path, "charts")
target_root = "dataset_final/train"

# Clean old
shutil.rmtree("dataset_final", ignore_errors=True)

os.makedirs(f"{target_root}/UP", exist_ok=True)
os.makedirs(f"{target_root}/DOWN", exist_ok=True)

up_images = []
down_images = []

# Collect images
for company in os.listdir(source_root):
    company_path = os.path.join(source_root, company)

    if not os.path.isdir(company_path):
        continue

    for label in ["up", "down"]:
        label_path = os.path.join(company_path, label)

        if not os.path.exists(label_path):
            continue

        for img in os.listdir(label_path):
            full_path = os.path.join(label_path, img)

            if label == "up":
                up_images.append((company, full_path))
            else:
                down_images.append((company, full_path))

print("Original → UP:", len(up_images), "DOWN:", len(down_images))

# Balance dataset
target_size = min(len(up_images), len(down_images))

up_sample = random.sample(up_images, target_size)
down_sample = random.sample(down_images, target_size)

# Copy files
for company, src in up_sample:
    shutil.copy(src, f"{target_root}/UP/{company}_{os.path.basename(src)}")

for company, src in down_sample:
    shutil.copy(src, f"{target_root}/DOWN/{company}_{os.path.basename(src)}")

print("Balanced →", target_size, "each")

